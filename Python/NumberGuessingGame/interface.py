#display menu
import random
LOWER_BOUND = 1
UPPER_BOUND = 100

def displaygreetings():
        print("\nWelcome to the Number Guessing Game!")

#get the user guess number
def get_user_guess():
    while True:
        print("\nenter your guess number between 1 and 100")
        user_guess = int(input())
        try:
            if LOWER_BOUND <= user_guess <= UPPER_BOUND:
                return user_guess
            else:
                print("\nuser guess is out of range")
                continue
        except ValueError:
            print("\nuser guess is not a valid number please enter a valid number")

# return random number generated by computer
def get_computer_choice():
    return random.randint(LOWER_BOUND, UPPER_BOUND)
